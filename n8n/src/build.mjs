// Builds the exported workflow JSON from readable Code-node sources, so the JavaScript that runs
// inside n8n is reviewed in one place. Run: pnpm n8n:build
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const here = import.meta.dirname;
const read = (name) => readFileSync(join(here, 'code', `${name}.js`), 'utf8');
// Code nodes cannot import modules, so the Convex helper is prepended wherever it is used.
const withHelper = (source) =>
  source.includes('postToConvex(') ? `${read('_convex')}\n${source}` : source;

const ERROR_WORKFLOW_ID = 'lendloopErrors01';
const SMTP = { smtp: { id: 'lendloopMailpit1', name: 'Mailpit (local SMTP)' } };
const SETTINGS = { executionOrder: 'v1', errorWorkflow: ERROR_WORKFLOW_ID, timezone: 'UTC' };
/** SMTP retries stay short: Convex waits for the answer of the notification workflow. */
const EMAIL_RETRY = { retryOnFail: true, maxTries: 2, waitBetweenTries: 1000 };

/** A Code node with JavaScript given inline. */
const inlineCodeNode = (name, source, position) => ({
  parameters: { jsCode: withHelper(source) },
  name,
  type: 'n8n-nodes-base.code',
  typeVersion: 2,
  position,
});

/** A Code node whose JavaScript lives in n8n/src/code/<file>.js. */
const codeNode = (name, file, position) => inlineCodeNode(name, read(file), position);

/** One write-back to Convex per item; the payload is built from the named upstream node. */
const reportNode = (name, { path, sourceNode, fields, status, position }) =>
  inlineCodeNode(
    name,
    `// Generated by n8n/src/build.mjs. Reports "${status}" without any error text (it can hold addresses).
for (const [index] of $input.all().entries()) {
  const source = $('${sourceNode}').itemMatching(index).json;
  await postToConvex(this.helpers, '${path}', {
    ${fields.map((field) => `${field}: source.${field},`).join('\n    ')}
    status: '${status}',${status === 'failed' ? "\n    error: 'The email could not be sent.'," : ''}
  });
}
return $input.all();
`,
    position,
  );

const sendEmail = (name, position) => ({
  parameters: {
    fromEmail: 'LendLoop <noreply@lendloop.local>',
    toEmail: '={{ $json.to }}',
    subject: '={{ $json.subject }}',
    emailFormat: 'text',
    text: '={{ $json.text }}',
    options: { appendAttribution: false },
  },
  name,
  type: 'n8n-nodes-base.emailSend',
  typeVersion: 2.1,
  position,
  credentials: SMTP,
  ...EMAIL_RETRY,
  // A failed send goes to the second output and is reported back as "failed".
  onError: 'continueErrorOutput',
});

const respond = (name, code, position, body) => ({
  parameters:
    body === undefined
      ? { respondWith: 'noData', options: { responseCode: code } }
      : { respondWith: 'json', responseBody: body, options: { responseCode: code } },
  name,
  type: 'n8n-nodes-base.respondToWebhook',
  typeVersion: 1.1,
  position,
});

const link = (to, index = 0) => ({ node: to, type: 'main', index });

/**
 * Convex -> n8n. The webhook answers only after the email went out (200) or failed (503), so a
 * failure is retried by the Convex outbox with backoff. The write-back runs after the answer.
 */
const notification = {
  id: 'lendloopNotify01',
  name: 'LendLoop – Loan notification',
  nodes: [
    {
      parameters: {
        httpMethod: 'POST',
        path: 'lendloop-loan-event',
        responseMode: 'responseNode',
        options: { rawBody: true },
      },
      name: 'Loan event from Convex',
      type: 'n8n-nodes-base.webhook',
      typeVersion: 2,
      position: [0, 300],
      webhookId: '6f1f0b8e-2d55-4c41-9a37-6c1a1f0e7b01',
    },
    codeNode('Verify signature', 'verify-convex-signature', [220, 300]),
    {
      parameters: {
        conditions: {
          options: { caseSensitive: true, leftValue: '', typeValidation: 'strict' },
          conditions: [
            {
              id: 'signature-valid',
              leftValue: '={{ $json.valid }}',
              rightValue: true,
              operator: { type: 'boolean', operation: 'true', singleValue: true },
            },
          ],
          combinator: 'and',
        },
        options: {},
      },
      name: 'Signed by Convex?',
      type: 'n8n-nodes-base.if',
      typeVersion: 2.2,
      position: [440, 300],
    },
    respond('Reject (401)', 401, [660, 460], '{"error":"unauthorized"}'),
    codeNode('Compose email', 'compose-notification', [660, 200]),
    sendEmail('Send email', [880, 200]),
    respond('Sent (200)', 200, [1100, 120]),
    respond('Not sent (503)', 503, [1100, 300]),
    reportNode('Report "sent"', {
      path: '/n8n/notification-acks',
      sourceNode: 'Compose email',
      fields: ['eventId'],
      status: 'sent',
      position: [1320, 120],
    }),
    reportNode('Report "failed"', {
      path: '/n8n/notification-acks',
      sourceNode: 'Compose email',
      fields: ['eventId'],
      status: 'failed',
      position: [1320, 300],
    }),
  ],
  connections: {
    'Loan event from Convex': { main: [[link('Verify signature')]] },
    'Verify signature': { main: [[link('Signed by Convex?')]] },
    'Signed by Convex?': { main: [[link('Compose email')], [link('Reject (401)')]] },
    'Compose email': { main: [[link('Send email')]] },
    'Send email': { main: [[link('Sent (200)')], [link('Not sent (503)')]] },
    'Sent (200)': { main: [[link('Report "sent"')]] },
    'Not sent (503)': { main: [[link('Report "failed"')]] },
  },
  settings: SETTINGS,
  active: true,
};

/** n8n -> Convex: daily overdue reminders with an idempotent write-back per loan and day. */
const overdue = {
  id: 'lendloopOverdue1',
  name: 'LendLoop – Overdue reminders',
  nodes: [
    {
      parameters: { rule: { interval: [{ field: 'cronExpression', expression: '0 9 * * *' }] } },
      name: 'Every day at 09:00 UTC',
      type: 'n8n-nodes-base.scheduleTrigger',
      typeVersion: 1.2,
      position: [0, 300],
    },
    {
      // Lets a reviewer run the reminders now from the editor or `n8n execute`.
      parameters: {},
      name: 'Run now',
      type: 'n8n-nodes-base.manualTrigger',
      typeVersion: 1,
      position: [0, 480],
    },
    codeNode('Fetch overdue loans', 'fetch-overdue-loans', [220, 300]),
    codeNode('Compose reminder', 'compose-reminder', [440, 300]),
    sendEmail('Send reminder', [660, 300]),
    reportNode('Report "sent"', {
      path: '/n8n/reminders',
      sourceNode: 'Compose reminder',
      fields: ['loanId', 'reminderKey'],
      status: 'sent',
      position: [880, 220],
    }),
    reportNode('Report "failed"', {
      path: '/n8n/reminders',
      sourceNode: 'Compose reminder',
      fields: ['loanId', 'reminderKey'],
      status: 'failed',
      position: [880, 400],
    }),
  ],
  connections: {
    'Every day at 09:00 UTC': { main: [[link('Fetch overdue loans')]] },
    'Run now': { main: [[link('Fetch overdue loans')]] },
    'Fetch overdue loans': { main: [[link('Compose reminder')]] },
    'Compose reminder': { main: [[link('Send reminder')]] },
    'Send reminder': { main: [[link('Report "sent"')], [link('Report "failed"')]] },
  },
  settings: SETTINGS,
  active: true,
};

/** Runs whenever another LendLoop workflow fails and tells Convex where, without the payload. */
const errors = {
  id: ERROR_WORKFLOW_ID,
  name: 'LendLoop – Error handler',
  nodes: [
    {
      parameters: {},
      name: 'A LendLoop workflow failed',
      type: 'n8n-nodes-base.errorTrigger',
      typeVersion: 1,
      position: [0, 300],
    },
    codeNode('Report to Convex', 'report-error', [220, 300]),
  ],
  connections: { 'A LendLoop workflow failed': { main: [[link('Report to Convex')]] } },
  settings: { executionOrder: 'v1', timezone: 'UTC' },
  // n8n only runs an error workflow that is published.
  active: true,
};

for (const workflow of [notification, overdue, errors]) {
  const file = join(here, '..', 'workflows', `${workflow.id}.json`);
  writeFileSync(file, `${JSON.stringify({ ...workflow, pinData: {}, tags: [] }, null, 2)}\n`);
}
